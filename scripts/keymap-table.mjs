const KEY_NAMES = {
  ArrowUp: '↑',
  ArrowDown: '↓',
  ArrowLeft: '←',
  ArrowRight: '→',
  Escape: 'Esc',
};

/** README notation of one shortcut on one OS: `Cmd+Shift+O`, `Ctrl+Tab`, `Shift+E`. */
function render(shortcut, os) {
  return shortcut
    .split(' ')
    .map((stroke) => {
      const plus = stroke.endsWith('++');
      const parts = plus ? [...stroke.slice(0, -2).split('+'), '+'] : stroke.split('+');
      const key = parts.pop();
      const mods = parts.map((m) => (m === 'Mod' ? (os === 'macos' ? 'Cmd' : 'Ctrl') : m));
      return [...mods, KEY_NAMES[key] ?? key].join('+');
    })
    .join(' ');
}

/** The cell of an action: one notation when all OS agree (`Cmd/Ctrl+O`), else per OS. */
function keysCell(id, keymaps) {
  const lists = Object.fromEntries(
    Object.entries(keymaps).map(([os, map]) => [os, (map[id] ?? []).map((s) => render(s, os))]),
  );
  const same = (a, b) => a.join() === b.join();
  const merged = (keymaps.macos[id] ?? []).map((s) =>
    render(s, 'macos')
      .replace(/^Cmd\+/, 'Cmd/Ctrl+')
      .replace(/ Cmd\+/g, ' Cmd/Ctrl+'),
  );
  const asWritten = (list) => list.map((s) => `\`${s}\``).join(', ');
  const portable =
    same(keymaps.macos[id] ?? [], keymaps.windows[id] ?? []) &&
    same(keymaps.windows[id] ?? [], keymaps.linux[id] ?? []);
  if (portable) return merged.length ? asWritten(merged) : '–';
  if (same(lists.macos, lists.windows) && same(lists.windows, lists.linux)) {
    return asWritten(lists.macos);
  }
  return `macOS ${asWritten(lists.macos)}, Windows/Linux ${asWritten(lists.windows)}`;
}

export function keymapTable(keymaps = { macos, windows, linux }) {
  const rows = ACTIONS.map((a) => {
    const text = README_TEXT[a.id];
    if (!text) throw new Error(`no README text for ${a.id}`);
    return `| ${keysCell(a.id, keymaps)} | ${text} |`;
  });
  return [START, '| Key | Action |', '|---|---|', ...rows, END].join('\n');
}

/** The README with the table replaced (throws without markers). */
export function withTable(readme, table = keymapTable()) {
  const from = readme.indexOf(START);
  const to = readme.indexOf(END);
  if (from < 0 || to < from) throw new Error('README.md has no keymap markers');
  return readme.slice(0, from) + table + readme.slice(to + END.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const path = new URL('../README.md', import.meta.url);
  const readme = readFileSync(path, 'utf8');
  const next = withTable(readme);
  if (process.argv.includes('--check')) {
    if (next !== readme) {
      console.error(
        'README.md: the shortcut table differs from the keymaps, run node scripts/keymap-table.mjs',
      );
      process.exit(1);
    }
  } else if (next !== readme) {
    writeFileSync(path, next);
    console.log('README.md: shortcut table written');
  }
}
